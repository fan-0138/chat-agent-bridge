/**
 * 判断这条消息是「聊天」还是「真要动手」。
 *
 * 为什么要分：聊天如果走完整 agent，她可能为了回一句话跑去翻日志、开浏览器，
 * 三分钟才憋出一个「这条处理超时了」。真人不会这样。
 * 所以聊天给短超时（超时就认输），明确让她干活的给长超时。
 *
 * 判断偏保守：只要像聊天就走短路。误判成聊天最多是超时一次；误判成任务就是让人干等。
 *
 * 2026-10-25 补的坑：像「你去试试吧」「为什么卡住了，告诉我，我去修」这种
 * 明明是要她动手的话，以前全被判成聊天 → 只给 60 秒 → 抖音那种要开浏览器、
 * 跑几条命令的活必然超时，她就只能回一句「卡住了，等下再弄」。
 */

const TASK_WORDS =
  /(帮我|帮忙|替我|给我(弄|搞|改|写|查|装|跑|删)|改一下|改改|修一下|修修|查一下|查查|跑一下|跑个|装一下|装上|部署|写个|写一下|删掉|删除|执行|排查|排错|重启|打开|抓一下|爬一下|git|npm|pnpm|node |python|bash|命令行|终端|脚本|日志|报错|异常|接口|api|数据库|端口|进程|服务|代码|仓库|分支|提交|测试|找点|找找|找一下|搜一下|搜搜|下载|保存|存一下|存进|收藏|表情包|贴纸|截图|试试|试一下|试下|试看|修好|修复|修它|修这个|去改|改掉|排查一下|检查一下|跑一遍)/i;

const TASK_PHRASES = /(看一下|看看|帮我看|你查|你试|你能查|需要你|你去试|你试试|去试试|试一下呗)/;

/**
 * 报问题的句子：这种八成是让她去查/去修，不是闲聊。
 * 只认「为什么/怎么 + 卡/慢/没反应/失败/报错」或「卡住了/没反应」这类明确带故障词的说法，
 * 不单独收「修/改/看看」——那话太泛，会把闲聊也拉进来。
 */
const PROBLEM_REPORT =
  /(为什么|咋|怎么|为啥).{0,8}(卡|慢|没反应|不反应|不动|没动|失败|报错|出错|挂了|超时|没成|不行|不通)|(卡住|卡了|卡在|堵住|超时|崩溃)/;

/**
 * @param {string} text
 * @returns {boolean}
 */
export function isTaskMessage(text) {
  const raw = String(text ?? '').trim();
  if (!raw) return false;
  if (raw.includes('```')) return true;
  if (raw.length > 400) return true; // 一大段话基本是在描述任务
  if (TASK_WORDS.test(raw)) return true;
  // 「看一下」这种本身两可，只有句子里还有具体对象（长一点）才算任务
  if (TASK_PHRASES.test(raw) && raw.length > 12) return true;
  // 在报故障：「为什么卡住了」「怎么没反应」
  if (PROBLEM_REPORT.test(raw) && raw.length >= 3 && raw.length <= 60) return true;
  return false;
}